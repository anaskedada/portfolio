// Regenerates src/components/icons.js from simple-icons (keeps only path + hex).
// Usage: npm run icons   — add a name to LIST to include a new logo.
import * as si from 'simple-icons';
import { writeFileSync } from 'node:fs';

const LIST = [
  'siPhp', 'siSymfony', 'siDoctrine', 'siMysql', 'siJavascript', 'siTypescript', 'siReact',
  'siVuedotjs', 'siHtml5', 'siCss', 'siWordpress', 'siWoocommerce', 'siPrestashop', 'siFlutter',
  'siDart', 'siFirebase', 'siStripe', 'siCloudflare', 'siGit', 'siGithub', 'siBitbucket',
  'siDocker', 'siJest', 'siVite', 'siJsonwebtokens',
];

let out = '// Generated by scripts/build-icons.mjs from simple-icons (CC0). Do not edit by hand.\n';
for (const name of LIST) {
  const icon = si[name];
  if (!icon) throw new Error(`Unknown icon: ${name}`);
  out += `export const ${name} = { hex: '${icon.hex}', path: '${icon.path}' };\n`;
}
writeFileSync(new URL('../src/components/icons.js', import.meta.url), out);
console.log(`Wrote ${LIST.length} icons`);
